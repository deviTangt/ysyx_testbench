module bcd7seg_AF(
    input      [3:0] b,
    output     [7:0] h,
    input en
);

wire b3,b2,b1,b0;
assign {b3,b2,b1,b0} = b;

wire [7 : 0] y;
assign h = en ? ~y : 8'hff;

MuxKeyWithDefault #(16, 4, 8) i0 (y, b, 8'h00, {
    4'd0,  8'b1111_1100,
    4'd1,  8'b0110_0000,
    4'd2,  8'b1101_1010,
    4'd3,  8'b1111_0010,
    4'd4,  8'b0110_0110,
    4'd5,  8'b1011_0110,
    4'd6,  8'b1011_1110,
    4'd7,  8'b1110_0000,
    4'd8,  8'b1111_1110,
    4'd9,  8'b1111_0110,
    4'd10, 8'b1110_1110,
    4'd11, 8'b0011_1110,
    4'd12, 8'b0001_1010,
    4'd13, 8'b0111_1010,
    4'd14, 8'b1101_1110,
    4'd15, 8'b1000_1110
  });

endmodule